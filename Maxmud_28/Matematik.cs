using System;
using static System.Math;

namespace Maxmud_28
{
    internal class Matematik
    {
        public static double qosh(double a, double b)
        {
            return a + b;
        }
        public static double ayir(double a, double b)
        {
            return a - b;
        }
        public static double kopaytir(double a, double b)
        {
            return a * b;
        }
        public static double bolish(double a, double b)
        {
            return a / b;
        }
        public static double daraja(double a, double b)
        {
            return Pow(a, b);
        }
       
    }
}
